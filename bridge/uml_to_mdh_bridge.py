#!/usr/bin/env python3
"""
Bridge: MDA UML activity diagram -> MDH algebraic spec.

Reads the real Papyrus/UML2 model that MDA's own ATL transform
(poisson_uml2cuda.atl) already consumes, and instead of transliterating each
recognized node into a literal CUDA statement (what the ATL rule does), emits
an MDH `md_hom` spec (.cpp) that describes the same computation algebraically.
MDH's own cuda_generator.hpp then does the actual kernel generation + tiling.

The recognized vocabulary below is the SAME vocabulary poisson_uml2cuda.atl
hardcodes (SelectNode / CheckBounds+BoundsDecision / ReadNeighbours /
ApplyStencil / StoreValue). This bridge is deliberately pattern-specific, not
a generic UML-to-anything translator: a new algorithm shape needs a new
recognizer, exactly like a new algorithm shape needs a new ATL rule.
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

UML_NS = "http://www.eclipse.org/uml2/5.0.0/UML"
XMI_NS = "http://www.omg.org/spec/XMI/20131001"
XMI_TYPE = f"{{{XMI_NS}}}type"

REQUIRED_NODES = {
    "InitialNode": "uml:InitialNode",
    "SelectNode": "uml:OpaqueAction",
    "CheckBounds": "uml:OpaqueAction",
    "BoundsDecision": "uml:DecisionNode",
    "ReadNeighbours": "uml:CallOperationAction",
    "ApplyStencil": "uml:CallOperationAction",
    "StoreValue": "uml:CallOperationAction",
    "ActivityFinalNode": "uml:ActivityFinalNode",
}


def find_poisson_activity(root: ET.Element) -> ET.Element:
    for behavior in root.iter("ownedBehavior"):
        if behavior.get(XMI_TYPE) == "uml:Activity" and behavior.get("name") == "PoissonActivity":
            return behavior
    raise SystemExit("ERROR: no uml:Activity named 'PoissonActivity' found in the model")


def recognize_nodes(activity: ET.Element) -> dict:
    """Walk the DIRECT node children of PoissonActivity and check the exact
    vocabulary poisson_uml2cuda.atl already hardcodes is present."""
    found = {}
    for node in activity.findall("node"):
        name = node.get("name")
        kind = node.get(XMI_TYPE)
        found[name] = kind

    missing = []
    for name, expected_kind in REQUIRED_NODES.items():
        actual_kind = found.get(name)
        if actual_kind is None:
            missing.append(f"{name} (missing)")
        elif actual_kind != expected_kind:
            missing.append(f"{name} (expected {expected_kind}, found {actual_kind})")

    if missing:
        raise SystemExit(
            "ERROR: UML model does not match the recognized MDA poisson pattern.\n"
            "The bridge refuses to guess silently. Missing/mismatched nodes:\n  - "
            + "\n  - ".join(missing)
        )

    # ReadNeighbours must produce the 4-neighbor cross (top/bot/left/right)
    read_neighbours = next(n for n in activity.findall("node") if n.get("name") == "ReadNeighbours")
    result_pins = {r.get("name") for r in read_neighbours.findall("result")}
    expected_pins = {"top", "bot", "left", "right"}
    if result_pins != expected_pins:
        raise SystemExit(
            f"ERROR: ReadNeighbours result pins are {result_pins}, "
            f"expected the 4-neighbor cross {expected_pins}"
        )

    return found


MDH_SPEC_TEMPLATE = '''// AUTO-GENERATED by bridge/uml_to_mdh_bridge.py - do not edit by hand.
//
// Source UML model : mda_reference/poisson_dsc.uml  (Activity: PoissonActivity)
// Recognized nodes  : {recognized_nodes}
//
// Node -> MDH construct mapping applied by the bridge:
//   SelectNode                  -> L(1), L(2)        (the two parallel index dims)
//   ReadNeighbours (top/bot/left/right) -> input_stencil_buffer 5-point cross
//   ApplyStencil (0.25*(...))   -> scalar_function f
//   StoreValue, no reduce loop  -> result_buffer, md_hom<2,0>
//
// Semantically identical to the hand-written kernels/poisson/spec/poisson.cpp
// in mdh-cuda-stencil-kernels - this file exists to prove the UML model can
// drive MDH's generator instead of Acceleo's naive text templates.

#include "md_hom_generator.hpp"

int main() {{
    auto U = md_hom::input_stencil_buffer(
        "U",
        {{md_hom::L(1), md_hom::L(2)}},
        md_hom::N(md_hom::N(0,1,0), md_hom::N(1,2,1), md_hom::N(0,1,0)),
        md_hom::oob::ZERO
    );

    auto SOURCE = md_hom::input_buffer("SOURCE", {{md_hom::L(1), md_hom::L(2)}});
    auto h2     = md_hom::input_scalar("h2");
    auto result = md_hom::result_buffer("U_new", {{md_hom::L(1), md_hom::L(2)}});

    auto f = md_hom::scalar_function(
        "return 0.25f * (U_val_l1_m1 + U_val_l1_p1 + U_val_l2_m1 + U_val_l2_p1 + SOURCE_val * h2_val);"
    );
    auto g = md_hom::scalar_function("return res;");

    auto md_hom_poisson = md_hom::md_hom<2, 0>(
        "poisson",
        md_hom::inputs(U, SOURCE, h2),
        f, g,
        result,
        false, false
    );

    auto generator = md_hom::generator::cuda_generator(md_hom_poisson);
    std::ofstream kernel_file;

    kernel_file.open("poisson_1.cu", std::fstream::out | std::fstream::trunc);
    kernel_file << generator.kernel_1();
    kernel_file.close();

    kernel_file.open("poisson_2.cu", std::fstream::out | std::fstream::trunc);
    kernel_file << generator.kernel_2();
    kernel_file.close();
}}
'''


def main():
    base = Path(__file__).resolve().parent.parent
    uml_path = base / "mda_reference" / "poisson_dsc.uml"
    out_path = base / "generated" / "poisson_from_uml.cpp"

    tree = ET.parse(uml_path)
    activity = find_poisson_activity(tree.getroot())
    found_nodes = recognize_nodes(activity)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        MDH_SPEC_TEMPLATE.format(recognized_nodes=", ".join(sorted(found_nodes)))
    )
    print(f"Recognized MDA poisson pattern in {uml_path}")
    print(f"Wrote MDH spec -> {out_path}")


if __name__ == "__main__":
    sys.exit(main())
